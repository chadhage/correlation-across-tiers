param([string]$ProjectRoot = (Split-Path (Split-Path $PSScriptRoot -Parent) -Parent))
$ErrorActionPreference = 'Stop'
$path = Join-Path $ProjectRoot 'config\versions.lock.json'
$lock = Get-Content -Raw -LiteralPath $path | ConvertFrom-Json
$hash = (Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash.ToLowerInvariant()
$lines = @('# Contoso frozen version inventory', '', '> Generated by tools\java\Freeze-Versions.ps1 from config\versions.lock.json. Do not edit independently.',
  '', "Lock SHA-256: ``$hash``", '', 'Status: **NOT CERTIFIED**. Archive/POM provenance is not live compatibility evidence.',
  '', '## Agent', '', "Agent: $($lock.agent.version); API: $($lock.agent.api); instrumentation: $($lock.agent.instrumentation).",
  '', "SHA-256: ``$($lock.agent.sha256)``", '', "Source: $($lock.agent.source)", '',
  '## Release pins', '', '| Component | Version | Source |', '|---|---|---|')
foreach ($release in $lock.releases) { $lines += "| $($release.name) | $($release.version) | $($release.source) |" }
$lines += @('', '## Portable validation tools', '')
foreach ($tool in $lock.portableTools.PSObject.Properties.Value) {
  $lines += "- $($tool.version): $($tool.source)"
}
$lines += @('', '## Resource APIs', '')
foreach ($api in $lock.resourceApis) { $lines += "- $($api.name): $($api.version); $($api.source)" }
$lines += @('', '## Compiler-only validation components', '')
foreach ($compiler in $lock.compilerTools) {
  $lines += "- $($compiler.name) $($compiler.version): $($compiler.source)"
  $lines += "- SHA-256 ``$($compiler.sha256)``; $($compiler.scope)"
}
$lines += @('', '## Contoso same-provider extension ABI', '')
foreach ($extension in $lock.extensions) {
  $lines += "- Module: $($extension.module); artifact $($extension.groupId):$($extension.artifactId):$($extension.version)"
  $lines += "- SDK ABI $($extension.sdkAbi), PROVIDED compiler APIs only: $($extension.compilerProvidedArtifacts -join ', ')"
  $lines += "- Provider service: $($extension.providerService); hash/loader status: $($extension.runtimeLoading)"
  $lines += "- SHA-256: ``$($extension.sha256)``; provider: $($extension.providerClass)"
  $lines += "- Loader argument: ``$($extension.runtimeLoaderArgument)``"
  $lines += "- Extension loader: $($extension.extensionLoader); delegate: $($extension.delegateClass) / $($extension.delegateLoader)"
  $lines += "- $($extension.vendorSupport)"
}
$lines += @('', '## Live VERIFYs — acceptance remains To Do', '')
foreach ($verify in $lock.liveVerifies) { $lines += "- VERIFY: $verify" }
[IO.File]::WriteAllLines((Join-Path $ProjectRoot 'VERSIONS.md'), $lines, [Text.UTF8Encoding]::new($false))
